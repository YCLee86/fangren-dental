import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = join(ROOT, 'preview', 'hero-zoom');

let html = readFileSync(join(ROOT, 'index.html'), 'utf8');

/* ---- 1. 相對路徑 ------------------------------------------------------- */
/* 「assets/」前面不是斜線的才換 —— JSON-LD 裡的 https://fangren.net/assets/…
   與 <link href="/assets/icon-192.png"> 都是絕對路徑，不能動。
   這一條同時吃掉 srcset 那三行（它們各自獨立一行，逐一命中）。 */
html = html.replace(/(^|[^/.])assets\//g, '$1../../assets/');
html = html.replace(/(href=")(posts\/)/g, '$1../../$2');
html = html.replace(/(href=")(site\.webmanifest)/g, '$1../../$2');
html = html.replace(/(href=")\.\/(")/g, '$1../../$2');

/* ---- 2. 計數器 --------------------------------------------------------- */
html = html.replace('<script src="../../assets/counter.js" defer></script>', '');
html = html.replace(
  '<p class="band-views" data-views-self="home">',
  '<p class="band-views">'
);
/* 內建的示範值掛勾（index.html 第 5196 行的註解就是在講這個）。
   ⚠ 這個屬性**絕對不要跟著版型搬回正式站**。 */
html = html.replace(
  '<span class="views-n" aria-hidden="true">0</span>',
  '<span class="views-n" aria-hidden="true" data-count="1024">0</span>'
);

/* ---- 3. 夾住溢出的那一層 ----------------------------------------------- */
/* 2026-08-15 電腦版上線時，index.html 自己已經有 .hero-shot 了
   （absolute inset:0 + overflow:hidden，只包 <img>），提案頁直接沿用。
   在這裡擋一下，免得哪天正式站把它拿掉、提案頁卻悄悄變成溢出。 */
if (!/class="hero-shot"/.test(html)) throw new Error('index.html 少了 .hero-shot');

/* ---- 4. noindex ＋ 推導註解 -------------------------------------------- */
/* ⚠ 要**換掉** SEO 區塊裡那一行，不是另外補一行 —— 兩行同時存在時
   document.querySelector('meta[name=robots]') 讀到的是前面那個 index,follow。
   （build.mjs 不會處理 preview/，所以改在這裡是安全的。） */
{
  const re = /<meta name="robots" content="index[^"]*">/;
  if (!re.test(html)) throw new Error('找不到 SEO 區塊的 robots');
  html = html.replace(re, '<meta name="robots" content="noindex, nofollow, noarchive">');
}

